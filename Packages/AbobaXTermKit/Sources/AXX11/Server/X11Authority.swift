import Foundation
import Security

/// The embedded server's MIT-MAGIC-COOKIE-1 and the files that carry it:
/// an Xauthority file for the server (and local clients), and a stand-in for
/// `xauth` that hands the cookie to ssh.
struct X11Authority: Equatable, Sendable {
    var cookie: [UInt8]

    static func random() -> X11Authority {
        var bytes = [UInt8](repeating: 0, count: 16)
        if SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes) != errSecSuccess {
            for i in bytes.indices { bytes[i] = UInt8.random(in: 0...255) }
        }
        return X11Authority(cookie: bytes)
    }

    var hex: String { cookie.map { String(format: "%02x", $0) }.joined() }

    init(cookie: [UInt8]) { self.cookie = cookie }

    init?(hex: String) {
        guard hex.count == 32 else { return nil }
        var bytes: [UInt8] = []
        var index = hex.startIndex
        while index < hex.endIndex {
            let next = hex.index(index, offsetBy: 2)
            guard let byte = UInt8(hex[index..<next], radix: 16) else { return nil }
            bytes.append(byte)
            index = next
        }
        cookie = bytes
    }

    /// Xauthority file with one wildcard entry (matches any host and display).
    var xauthorityFile: Data {
        var data = Data()
        func field(_ bytes: [UInt8]) {
            data.append(UInt8(bytes.count >> 8))
            data.append(UInt8(bytes.count & 0xFF))
            data.append(contentsOf: bytes)
        }
        data.append(contentsOf: [0xFF, 0xFF]) // FamilyWild
        field([])
        field([])
        field(Array("MIT-MAGIC-COOKIE-1".utf8))
        field(cookie)
        return data
    }

    /// Shell script used as ssh's `XAuthLocation`. ssh runs `xauth list <display>`
    /// and reads "<name> <protocol> <hex cookie>" from the first line.
    func xauthShim(display: Int) -> String {
        """
        #!/bin/sh
        # Generated by AbobaXTerm: answers ssh's "xauth list" with the cookie of the embedded X server.
        echo "abobaxterm/unix:\(display)  MIT-MAGIC-COOKIE-1  \(hex)"

        """
    }
}
